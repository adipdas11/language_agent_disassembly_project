import { expect, test } from '@playwright/test'

test('the six stages connect the four-field state to a decision, request and verified failure', async ({ page }) => {
  await page.goto('/#state')
  const stages = page.getByRole('navigation', { name: 'Planning walkthrough stages' }).getByRole('button')
  await expect(stages).toHaveCount(6)
  await stages.nth(1).click()
  const state = JSON.parse((await page.locator('.process-code').textContent())!)
  expect(Object.keys(state)).toEqual(['global_view', 'local_view', 'assembly_state', 'force_torque'])
  expect(state.assembly_state.last_outcome).toBe('failure')
  expect(state.assembly_state.removed).toEqual([])
  await expect(page.locator('.state-source')).toHaveCount(4)
  for (const source of await page.locator('.state-source').all()) expect(await source.evaluate(node => getComputedStyle(node).opacity)).toBe('1')
  await stages.nth(2).click()
  await expect(page.locator('.process-code')).toContainText('SYSTEM INSTRUCTION')
  await expect(page.locator('.process-code')).toContainText('"last_outcome": "failure"')
  await expect(page.locator('.context-insertion')).toBeVisible()
  await stages.nth(3).click()
  const decision = JSON.parse((await page.locator('.process-code').textContent())!)
  expect(decision.next_action).toBe('unscrew')
  expect(decision.target).toBe(state.local_view.target)
  await stages.nth(4).click()
  const request = JSON.parse((await page.locator('.process-code').textContent())!)
  expect(request.skill).toBe(decision.next_action)
  expect(request.target).toBe(decision.target)
  expect(request).toHaveProperty('expected_effect')
  expect(request).toHaveProperty('verification')
  expect(request).toHaveProperty('on_failure')
  await stages.nth(5).click()
  const feedback = JSON.parse((await page.locator('.process-code').textContent())!)
  expect(feedback.assembly_state.last_outcome).toBe('failure')
  expect(feedback.assembly_state.removed).toEqual([])
  await expect(page.locator('.verification-result')).toContainText('Removal not confirmed')
  await expect(page.locator('.process-execution video')).not.toHaveAttribute('controls')
  await page.getByRole('button', { name: 'Next stage', exact: true }).click()
  await expect(page.locator('.planning-walkthrough')).toHaveAttribute('data-stage', 'perception')
})

test('lines reveal quickly, pause freezes them, and replay resets the sequence', async ({ page }) => {
  await page.clock.install()
  await page.goto('/#state')
  const board = page.locator('.planning-walkthrough')
  await board.scrollIntoViewIfNeeded()
  await expect(board).toHaveClass(/is-running/)
  await page.clock.runFor(1800)
  const before = (await page.locator('.process-code').textContent())!.length
  expect(before).toBeGreaterThan(10)
  await page.getByRole('button', { name: 'Pause walkthrough', exact: true }).click()
  const paused = await page.locator('.process-code').textContent()
  await page.clock.runFor(3000)
  expect(await page.locator('.process-code').textContent()).toBe(paused)
  await page.getByRole('button', { name: 'Play walkthrough', exact: true }).click()
  await page.clock.runFor(2500)
  expect(JSON.parse((await page.locator('.process-code').textContent())!)).toHaveProperty('scene')
  await page.clock.runFor(9000)
  await expect(board).toHaveAttribute('data-stage', 'state')
  await page.locator('#top').scrollIntoViewIfNeeded()
  await expect(board).toHaveClass(/is-paused/)
  await page.clock.runFor(15000)
  await expect(board).toHaveAttribute('data-stage', 'state')
  await board.scrollIntoViewIfNeeded()
  await expect(board).toHaveClass(/is-running/)
  await page.getByRole('button', { name: 'Replay walkthrough', exact: true }).click()
  await expect(board).toHaveAttribute('data-stage', 'perception')
  await expect(board).toHaveClass(/is-running/)
  expect((await page.locator('.process-code').textContent())!.length).toBeLessThan(before)
})

test('reduced motion shows complete content and manual stage controls', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/#state')
  const board = page.locator('.planning-walkthrough')
  await expect(board).toHaveClass(/is-paused/)
  const code = await page.locator('.process-code').textContent()
  expect(JSON.parse(code!)).toHaveProperty('scene')
  await expect(page.getByRole('button', { name: 'Pause walkthrough', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Next stage', exact: true }).click()
  await expect(board).toHaveAttribute('data-stage', 'state')
  expect(JSON.parse((await page.locator('.process-code').textContent())!)).toHaveProperty('force_torque')
})

test('schema and prompt references expand without leaving the page', async ({ page }) => {
  await page.goto('/#state')
  await expect(page.locator('.schema-reference')).not.toHaveAttribute('open')
  await page.locator('.schema-reference > summary').click()
  await expect(page.getByRole('button', { name: 'Copy state JSON', exact: true })).toBeVisible()
  await page.locator('#prompts').scrollIntoViewIfNeeded()
  await expect(page.locator('.prompt-template[open]')).toHaveCount(0)
  await page.locator('.prompt-template > summary').filter({ hasText: 'Reasoning and selection' }).click()
  await expect(page.locator('.prompt-template[open] .prompt-prose')).toContainText('{state_packet}')
  await expect(page.getByRole('button', { name: 'Copy Reasoning and selection', exact: true })).toBeVisible()
})
