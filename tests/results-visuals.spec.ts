import { expect, test } from '@playwright/test'

test('failure plots switch metrics without mixing counts and recovery rates', async ({ page }) => {
  await page.goto('/#results')
  const plot = page.getByLabel('Scripted and agentic failure comparison', { exact: true })
  await expect(plot).toContainText('Failures propagated to later targets')
  await expect(plot.locator('.count-device-plot').last()).toContainText('3.8')
  await expect(plot.locator('.count-device-plot').last()).toContainText('0.3')
  await page.getByRole('group', { name: 'Failure metric' }).getByRole('button', { name: 'Physical assistance', exact: true }).click()
  await expect(plot).toContainText('Operator interventions')
  await expect(plot.locator('.count-device-plot').last()).toContainText('4.2')
  await expect(plot.locator('.count-device-plot').last()).toContainText('0.7')
  await expect(plot.locator('.count-device-plot').first().locator('.mean-bar-zero')).toHaveCount(1)
  await expect(page.getByLabel('Agentic recovery ratios', { exact: true })).toContainText('95.8%')
  await expect(page.getByLabel('Agentic recovery ratios', { exact: true })).toContainText('8 eligible trials')
})

test('skill visuals preserve success denominators and recovery-call accounting', async ({ page }) => {
  await page.goto('/#results')
  await page.getByRole('group', { name: 'Skill execution device' }).getByRole('button', { name: 'Laptop', exact: true }).click()
  await expect(page.locator('.skill-result-card')).toHaveCount(2)
  const extraction = page.getByLabel('Laptop: Pick & Extract', { exact: true })
  await expect(extraction).toContainText('76.7%')
  await expect(extraction).toContainText('23 / 30')
  await expect(extraction).toContainText('40 total')
  await expect(extraction).toContainText('10 recovery')
  await expect(extraction).toContainText('14.6 s')
  await page.getByRole('group', { name: 'Skill execution device' }).getByRole('button', { name: 'Additional HDD', exact: true }).click()
  await expect(page.locator('.skill-result-card')).toHaveCount(3)
  await expect(page.getByLabel('Additional HDD: Flip', { exact: true })).toContainText('9 / 10')
})

test('HDD transfer and perception use the reported values and retain the complete tables', async ({ page }) => {
  await page.goto('/#results')
  await expect(page.getByLabel('HDD comparison: Autonomous completion', { exact: true })).toContainText('90.9%')
  await expect(page.getByLabel('HDD comparison: Cycle time', { exact: true })).toContainText('279.0 s')
  const trackWidths = await page.locator('.hdd-highlight .mean-bar-track').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().width))
  expect(trackWidths.every(width => width > 80)).toBe(true)
  await expect(page.getByLabel('RF-DETR-Large: AP@0.5:0.95', { exact: true })).toContainText('61.5%')
  await page.getByRole('group', { name: 'Detection evaluation metric' }).getByRole('button', { name: 'Precision', exact: true }).click()
  await expect(page.getByLabel('RF-DETR-Large: Precision', { exact: true })).toContainText('96.38%')
  await expect(page.locator('.classifier-class-grid')).toContainText('40 / 41 correct')
  await expect(page.locator('.classifier-class-grid')).toContainText('39 / 40 correct')
  await expect(page.locator('.results-reference[open]')).toHaveCount(0)
  await page.locator('.results-reference > summary').filter({ hasText: 'Full per-skill table' }).click()
  await expect(page.locator('.skill-table')).toBeVisible()
  await expect(page.locator('.skill-table tbody tr')).toHaveCount(10)
})
